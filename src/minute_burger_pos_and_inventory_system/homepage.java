    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        javax.swing.JLabel title = new javax.swing.JLabel("Log out of Minute Burger?");
        title.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 23));
        title.setForeground(new java.awt.Color(45, 48, 56));
        javax.swing.JLabel detail = new javax.swing.JLabel("Your current session will end. You can sign in again anytime.");
        detail.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 16));
        detail.setForeground(new java.awt.Color(90, 96, 105));
        javax.swing.JPanel message = new javax.swing.JPanel(new java.awt.GridLayout(2, 1, 0, 14));
        message.setBorder(javax.swing.BorderFactory.createEmptyBorder(20, 20, 20, 20));
        message.add(title);
        message.add(detail);
        Object[] choices = {"Yes, Log Out", "Stay Logged In"};
        int choice = javax.swing.JOptionPane.showOptionDialog(this, message,
                "Confirm Logout", javax.swing.JOptionPane.DEFAULT_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE, null, choices, choices[1]);
        if (choice != 0) return;

        // Construct login first; do not clear the session if navigation fails.
        try {
            login loginFrame = new login();
            java.awt.Dimension screenSize = java.awt.Toolkit.getDefaultToolkit().getScreenSize();
            loginFrame.setBounds(0, 0, screenSize.width, screenSize.height);
            loginFrame.setVisible(true);
            SharedData.currentUserFullName = null;
            SharedData.currentUserRole = null;
            this.dispose();
        } catch (RuntimeException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Unable to open login", ex);
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Unable to open Login. Please try again.\n" + ex.getMessage(),
                    "Logout Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton8ActionPerformed

