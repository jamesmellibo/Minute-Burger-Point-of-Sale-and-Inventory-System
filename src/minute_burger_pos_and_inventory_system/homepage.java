    // HELPER METHOD PARA SA DISPLAY UG CLOCK
    private void displayUserAndClock(String fullName, String role) {
        // 1. DYNAMIC GREETING
        if (lblWelcome != null) {
            lblWelcome.setText("Hello, " + fullName + "!");
        }

        // 2. DYNAMIC ROLE BADGE
        if (admin != null) {
            if (role != null && role.equalsIgnoreCase("Staff")) {
                admin.setText("[ Staff ]");
            } else {
                admin.setText("[ Admin ]");
            }
        }

        // 3. REAL-TIME CLOCK SETUP
        if (lblDateTime != null) {
            SimpleDateFormat sdf = new SimpleDateFormat("EEEE, MMM dd, yyyy - hh:mm:ss a");
            lblDateTime.setText(" " + sdf.format(new Date()) + " ");
            lblDateTime.setOpaque(true);
            lblDateTime.setBackground(new java.awt.Color(245, 245, 245));
            lblDateTime.setForeground(new java.awt.Color(80, 80, 80));
            lblDateTime.setBorder(javax.swing.BorderFactory.createLineBorder(new java.awt.Color(210, 210, 210), 1, true));

            Timer timer = new Timer(1000, e -> lblDateTime.setText(" " + sdf.format(new Date()) + " "));
            timer.start();
        }
    }




    




